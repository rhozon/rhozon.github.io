/* Interactive part of the multi-agent commodity analyst case. Plain JavaScript + Chart.js, from
   data.json (written by scripts/exportar_site.py, from real runs of the pipeline with the R core,
   in demonstration mode) and guard.js (the anti-hallucination guard, ported from Python). */
(function () {
  var root = document.getElementById('agro-app');
  if (!root) return;
  var PT = (document.documentElement.lang || '').toLowerCase().indexOf('pt') === 0;
  var T = PT ? {
    tabs: ['Refaça uma execução', 'Teste a trava', 'Relatório final'],
    commodity: 'Commodity', milho: 'Milho', soja: 'Soja', price: 'Preço na CBOT (US¢ por bushel)',
    s1: 'Coletor', s1d: 'Janela escolhida', s2: 'Econometrista', s3: 'Crítico', rej: 'reprovado', ok: 'aprovado', s4: 'Backtest', s5: 'Redator', s6: 'Trava anti-alucinação',
    tries: 'tentativa', obs: 'observações', src: 'Fonte trocada', lb: 'Ljung-Box, p', arch: 'ARCH-LM, p', volLong: 'Volatilidade estrutural', volNow: 'Volatilidade atual',
    mape: 'MAPE do modelo', rw: 'passeio aleatório', cov: 'Cobertura do intervalo de 95%', h: 'passos à frente',
    s5d: 'escreve previsão, drivers e implicação; no modo de demonstração o texto é fixo e sem números.', s6d: 'confere cada número do texto contra os valores calculados pelo núcleo; passou.',
    guardIntro: 'Escreva ou edite um parágrafo como o Redator escreveria. A trava confere cada número contra os valores que o núcleo em R calculou para esta execução.',
    presets: 'Exemplos', okL: 'tem origem', invL: 'inventado', ambL: 'ambíguo', maskL: 'data ou ordem de modelo', verdict: 'Veredito',
    pass: 'Passou: todo número do texto tem origem nos resultados.', fail: 'Bloqueado: há número sem origem, e o relatório não sairia.', amb: 'Bloqueado: separador de milhar ambíguo; reescreva sem ele.',
    allowed: 'Valores autorizados nesta execução', parity: 'Esta versão em JavaScript decidiu igual à trava em Python em', parity2: 'números das frases de exemplo.',
    from: 'origem', reportNote: 'Relatório gerado pelo sistema, como sai em examples/ no repositório.', loading: 'Carregando...'
  } : {
    tabs: ['Replay a run', 'Test the guard', 'Final report'],
    commodity: 'Commodity', milho: 'Corn', soja: 'Soybeans', price: 'CBOT price (US¢ per bushel)',
    s1: 'Collector', s1d: 'Window chosen', s2: 'Econometrician', s3: 'Critic', rej: 'rejected', ok: 'approved', s4: 'Backtest', s5: 'Writer', s6: 'Anti-hallucination guard',
    tries: 'attempt', obs: 'observations', src: 'Source switched', lb: 'Ljung-Box, p', arch: 'ARCH-LM, p', volLong: 'Long-run volatility', volNow: 'Current volatility',
    mape: 'Model MAPE', rw: 'random walk', cov: 'Coverage of the 95% interval', h: 'steps ahead',
    s5d: 'writes forecast, drivers and implication; in demonstration mode the text is fixed and has no numbers.', s6d: 'checks every number in the text against the values the core computed; passed.',
    guardIntro: 'Write or edit a paragraph the way the Writer would. The guard checks every number against the values the R core computed for this run. The system writes in Portuguese, so the rules for dates and counts read Portuguese words.',
    presets: 'Examples', okL: 'has a source', invL: 'invented', ambL: 'ambiguous', maskL: 'date or model order', verdict: 'Verdict',
    pass: 'Passed: every number in the text has a source in the results.', fail: 'Blocked: a number has no source, and the report would not go out.', amb: 'Blocked: ambiguous thousands separator; rewrite without it.',
    allowed: 'Values allowed in this run', parity: 'This JavaScript version decided the same as the Python guard on', parity2: 'numbers in the example sentences.',
    from: 'source', reportNote: 'Report generated by the system, as it appears in examples/ in the repository, in Portuguese.', loading: 'Loading...'
  };
  function tr(s) {
    if (PT) return s;
    return s.replace(/ARCH-LM rejeita homocedasticidade dos residuos \(p=([\d.]+) < ([\d.]+)\): ha heterocedasticidade nao capturada pelo modelo/,
        'ARCH-LM rejects homoscedasticity of the residuals (p=$1 < $2): volatility clustering the model did not capture')
      .replace(/Ljung-Box rejeita .*?\(p=([\d.]+) < ([\d.]+)\).*$/, 'Ljung-Box finds autocorrelation left in the residuals (p=$1 < $2)')
      .replace(/o modelo previu zero por construcao \(media zero na especificacao\) e empatou com o passeio aleatorio no ponto/,
        'by construction the model forecasts zero (zero mean in the specification), so it ties the random walk on the point forecast')
      .replace(/CEPEA indisponivel \(coleta CEPEA nao implementada nesta versao\); relatorio segue so com a serie internacional/,
        'CEPEA unavailable (not implemented in this version); the report uses the international series only');
  }
  function fmt(x, d) { return Number(x).toLocaleString(PT ? 'pt-BR' : 'en-US', {minimumFractionDigits: d || 0, maximumFractionDigits: d || 0}); }
  function el(tag, attrs, html) { var e = document.createElement(tag); for (var k in (attrs || {})) e.setAttribute(k, attrs[k]); if (html != null) e.innerHTML = html; return e; }
  function esc(s) { return String(s).replace(/[&<>"]/g, function (c) { return {'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;'}[c]; }); }
  function control(parent, label, input) { var w = el('label', {class: 'agro-ctl'}); w.appendChild(el('span', {}, label)); w.appendChild(input); parent.appendChild(w); return input; }
  function select(opts, val) { var s = el('select'); opts.forEach(function (o) { var op = el('option', {value: o[0]}, o[1]); if (o[0] === val) op.selected = true; s.appendChild(op); }); return s; }
  function card(parent, label) { var c = el('div', {class: 'agro-card'}); c.appendChild(el('div', {class: 'agro-card-l'}, label)); var v = el('div', {class: 'agro-card-v'}); c.appendChild(v); var s = el('div', {class: 'agro-card-s'}); c.appendChild(s); parent.appendChild(c); return {v: v, s: s}; }
  function md(src) {
    var out = [], list = false;
    src.replace(/\r/g, '').split(/\n\s*\n/).forEach(function (b) {
      b = b.trim(); if (!b) return;
      if (/^!\[/.test(b)) return;
      var inline = function (s) { return esc(s).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>').replace(/`([^`]+)`/g, '<code>$1</code>'); };
      var h = /^(#{1,3})\s+(.*)$/.exec(b);
      if (h) { out.push('<h' + (h[1].length + 3) + '>' + inline(h[2]) + '</h' + (h[1].length + 3) + '>'); return; }
      if (/^>\s?/.test(b)) { out.push('<blockquote>' + inline(b.replace(/^>\s?/gm, '')) + '</blockquote>'); return; }
      if (/^\d+\.\s/.test(b)) { out.push('<ol>' + b.split(/\n(?=\d+\.\s)/).map(function (li) { return '<li>' + inline(li.replace(/^\d+\.\s/, '')) + '</li>'; }).join('') + '</ol>'); return; }
      out.push('<p>' + inline(b).replace(/\n/g, ' ') + '</p>');
    });
    return out.join('');
  }

  root.appendChild(el('p', {}, T.loading));
  fetch(root.getAttribute('data-src')).then(function (r) { return r.json(); }).then(build).catch(function (e) { root.innerHTML = '<p>data.json: ' + e + '</p>'; });

  function build(D) {
    root.innerHTML = '';
    var top = el('div', {class: 'agro-ctls'}); root.appendChild(top);
    var sC = control(top, T.commodity, select([['milho', T.milho], ['soja', T.soja]], 'soja'));
    var nav = el('div', {class: 'agro-tabs'}); root.appendChild(nav);
    var panes = T.tabs.map(function (t, i) { var b = el('button', {type: 'button'}, t); nav.appendChild(b); var p = el('div', {class: 'agro-pane'}); root.appendChild(p); b.addEventListener('click', function () { show(i); }); return {b: b, p: p}; });
    var cur = 0, views = [replay(panes[0].p), guardView(panes[1].p), report(panes[2].p)];
    function show(i) { cur = i; panes.forEach(function (x, j) { x.p.style.display = i === j ? 'block' : 'none'; x.b.classList.toggle('on', i === j); }); views[i](D.commodities[sC.value]); }
    sC.addEventListener('change', function () { show(cur); });
    show(0);
    var n = 0, same = 0;
    Object.keys(D.commodities).forEach(function (c) {
      var R = D.commodities[c];
      R.frases.forEach(function (f) { var js = agroGuard.verificar(f.texto, R.valores); f.numeros.forEach(function (x, i) { n++; if (js[i] && js[i].token === x.token && js[i].veredito === x.veredito) same++; }); });
    });
    root.appendChild(el('p', {class: 'agro-note'}, T.parity + ' ' + same + ' / ' + n + ' ' + T.parity2));
  }

  function replay(p) {
    var steps = el('ol', {class: 'agro-steps'}); p.appendChild(steps);
    var cards = el('div', {class: 'agro-cards'}); p.appendChild(cards);
    var cV = card(cards, T.volLong), cN = card(cards, T.volNow), cL = card(cards, T.lb + ' / ' + T.arch), cM = card(cards, T.mape), cK = card(cards, T.cov);
    var box = el('div', {class: 'agro-chart'}); var cv = el('canvas'); box.appendChild(cv); p.appendChild(box);
    var tc = getComputedStyle(root).color;
    var chart = new Chart(cv, {type: 'line', data: {labels: [], datasets: []}, options: {responsive: true, maintainAspectRatio: false, animation: false, interaction: {mode: 'index', intersect: false},
      plugins: {legend: {labels: {color: tc, boxWidth: 14}}}, scales: {x: {ticks: {color: tc, maxTicksLimit: 8, maxRotation: 0}, grid: {display: false}}, y: {ticks: {color: tc}, grid: {color: 'rgba(127,127,127,.15)'}}}}});
    return function (R) {
      var f = R.fit, b = R.backtest, li = [];
      li.push('<li><strong>' + T.s1 + '</strong>: ' + T.s1d + ' ' + R.janela.inicio + ' / ' + R.janela.fim + ', ' + fmt(R.janela.n_obs) + ' ' + T.obs + '.' +
        (R.janela.trocas.length ? '<br><span class="agro-warn">' + T.src + ': ' + esc(tr(R.janela.trocas.join('; '))) + '</span>' : '') + '</li>');
      var k = 0;
      R.reprovacoes.forEach(function (r) {
        k++;
        li.push('<li><strong>' + T.s2 + '</strong> (' + T.tries + ' ' + k + '): <code>' + esc(r.familia) + '</code></li>');
        li.push('<li class="bad"><strong>' + T.s3 + '</strong>: ' + T.rej + '. <em>' + esc(tr(r.motivos.join('; '))) + '</em></li>');
      });
      k++;
      li.push('<li><strong>' + T.s2 + '</strong> (' + T.tries + ' ' + k + '): <code>' + esc(f.familia) + '</code></li>');
      li.push('<li class="good"><strong>' + T.s3 + '</strong>: ' + (R.aprovado ? T.ok : T.rej) + '. ' + T.lb + ' ' + fmt(f.ljung_box, 4) + ', ' + T.arch + ' ' + fmt(f.arch_lm, 4) + '.</li>');
      if (b) li.push('<li><strong>' + T.s4 + '</strong>: ' + b.horizonte + ' ' + T.h + '. <em>' + esc(tr(b.nota)) + '</em></li>');
      li.push('<li><strong>' + T.s5 + '</strong>: ' + T.s5d + '</li>');
      li.push('<li class="good"><strong>' + T.s6 + '</strong>: ' + T.s6d + '</li>');
      steps.innerHTML = li.join('');
      cV.v.textContent = fmt(f.vol_por_regime[0], 4); cV.s.textContent = f.familia.toUpperCase();
      cN.v.textContent = fmt(f.vol_atual, 4); cN.s.textContent = '';
      cL.v.textContent = fmt(f.ljung_box, 2) + ' / ' + fmt(f.arch_lm, 2); cL.s.textContent = '> 0' + (PT ? ',' : '.') + '05';
      if (b) { cM.v.textContent = fmt(b.mape, 2) + '%'; cM.s.textContent = T.rw + ': ' + fmt(b.mape_baseline, 2) + '%'; cK.v.textContent = fmt(100 * b.cobertura_ic, 0) + '%'; cK.s.textContent = b.horizonte + ' ' + T.h; }
      chart.data.labels = R.serie.datas; chart.data.datasets = [{label: T.price, data: R.serie.cbot, borderColor: '#0f766e', borderWidth: 1.5, pointRadius: 0}];
      chart.update();
    };
  }

  function guardView(p) {
    p.appendChild(el('p', {class: 'agro-note'}, T.guardIntro));
    var pre = el('div', {class: 'agro-presets'}); p.appendChild(pre);
    var ta = el('textarea', {rows: 4, class: 'agro-ta', spellcheck: 'false'}); p.appendChild(ta);
    var out = el('div', {class: 'agro-out'}); p.appendChild(out);
    var verdict = el('p', {class: 'agro-verdict'}); p.appendChild(verdict);
    var leg = el('p', {class: 'agro-legend'}, '<span class="v-ok">' + T.okL + '</span> <span class="v-inventado">' + T.invL + '</span> <span class="v-ambiguo">' + T.ambL + '</span> <span class="v-mascara">' + T.maskL + '</span>'); p.appendChild(leg);
    var det = el('details', {class: 'agro-allowed'}); det.appendChild(el('summary', {}, T.allowed)); var tb = el('table'); det.appendChild(tb); p.appendChild(det);
    var R = null;
    function run() {
      var t = ta.value, res = agroGuard.verificar(t, R.valores), html = '', last = 0;
      res.forEach(function (x) {
        html += esc(t.slice(last, x.inicio)) + '<mark class="v-' + x.veredito + '" title="' + (x.rotulos && x.rotulos.length ? T.from + ': ' + esc(x.rotulos.join(', ')) : esc(x.veredito)) + '">' + esc(x.token) + '</mark>';
        last = x.inicio + x.token.length;
      });
      out.innerHTML = (html + esc(t.slice(last))).replace(/\n/g, '<br>');
      var inv = res.some(function (x) { return x.veredito === 'inventado'; }), amb = res.some(function (x) { return x.veredito === 'ambiguo'; });
      verdict.textContent = T.verdict + ': ' + (amb ? T.amb : inv ? T.fail : T.pass);
      verdict.className = 'agro-verdict ' + (amb || inv ? 'bad' : 'good');
    }
    ta.addEventListener('input', run);
    return function (r) {
      R = r; pre.innerHTML = '<span>' + T.presets + ':</span>';
      r.frases.forEach(function (f, i) { var b = el('button', {type: 'button'}, String(i + 1)); b.title = f.texto; b.addEventListener('click', function () { ta.value = f.texto; run(); }); pre.appendChild(b); });
      tb.innerHTML = r.valores.map(function (v) { return '<tr><td><code>' + esc(v[0]) + '</code></td><td>' + esc(String(v[1])) + '</td></tr>'; }).join('');
      ta.value = r.frases[2].texto + ' ' + r.frases[3].texto + ' ' + r.frases[8].texto;
      run();
    };
  }

  function report(p) {
    p.appendChild(el('p', {class: 'agro-note'}, T.reportNote));
    var box = el('div', {class: 'agro-report'}); p.appendChild(box);
    return function (R) { box.innerHTML = md(R.relatorio); };
  }
})();
